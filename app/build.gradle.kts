// Read the CMF API key from local.properties (never committed). Falls back to an
// empty string, in which case the app uses only the secondary data source.
val cmfApiKey: String = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}.getProperty("CMF_API_KEY", "").trim()

// Release signing comes from keystore.properties, which is not committed.
// Without it the release variant simply builds unsigned.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

